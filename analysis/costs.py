#!/usr/bin/env python3
"""Build docs/COSTS.md: what one answer costs, and what building the project cost.

Sources: runs/*.jsonl (cost_usd per question, written by eval.py), the paid-call ledgers
cache/llm_spend.jsonl and cache/generic/spend.jsonl, and analysis/infra.json (cloud machines).
Claude calls made through the Claude Code CLI are priced by the CLI at API list price.
"""
import datetime as dt
import glob
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
os.chdir(ROOT)
now = dt.datetime.now(dt.timezone.utc)
OURS = os.environ.get("BP_OURS_RUN", "router_full_test_v8")


def run_cost(name):
    f = Path(f"runs/{name}.jsonl")
    if not f.exists():
        return None
    R = [json.loads(l) for l in open(f)]
    return len(R), sum(float(r.get("cost_usd") or 0) for r in R)


def ledger(path):
    if not Path(path).exists():
        return 0.0
    return sum(float(json.loads(l).get("cost_usd") or 0) for l in open(path))


def _local_compute():
    """$ per 1k questions of local compute and the mean detector time per drawing, from analysis/tables.py's
    outputs (analysis/out/overall.csv, latency.csv) for the canonical run."""
    import csv

    compute_1k = drawing_s = float("nan")
    for r in csv.DictReader(open("analysis/out/overall.csv")):
        if r["run"] == OURS:
            compute_1k = float(r["compute_usd_per_1k"])
    for r in csv.DictReader(open("analysis/out/latency.csv")):
        if r["run"] == OURS and r["solver"] == "CubiCasa detector · slowest per drawing":
            drawing_s = float(r["mean"])
    return compute_1k, drawing_s


compute_1k, drawing_s = _local_compute()

lines = ["# Costs", "", f"_Generated by `analysis/costs.py` at {now:%Y-%m-%d %H:%M} UTC. Re-run it to refresh._", ""]

# --- per-answer cost of the product
lines += ["## What one answer costs", "",
          f"Measured on all 25,420 held-out test questions (`runs/{OURS}`), at API list price.", "",
          "| | questions | API $ | $ per 1,000 questions |", "|---|---|---|---|"]
ours = run_cost(OURS)
if ours:
    n, c = ours
    lines.append(f"| **Datum** (router) | {n:,} | ${c:.2f} | **${c / n * 1000:.3f}** |")
for name, label in [("baseline_sonnetfair_full400", "Claude Sonnet 5.5 + sibling CAD/IFC files"),
                    ("baseline_sonnet_full400", "Claude Sonnet 5.5, drawing only"),
                    ("baseline_haiku_full400", "Claude Haiku 5.5, drawing only"),
                    ("baseline_gemini_full400", "Gemini 3.1 Pro, drawing only"),
                    ("baseline_nemotron_full400", "Nemotron 3.5 Super VL (open, partner price)")]:
    rc = run_cost(name)
    if rc:
        n, c = rc
        lines.append(f"| {label} | {n:,} (sample) | ${c:.2f} | ${c / n * 1000:.2f} |")
lines += ["",
          "Frontier rows are a 400-question stratified sample of the same test split; their $/1k is the raw sample "
          "mean. The sample over-represents the costly IFC and free-text cells, so re-weighted to the true test mix "
          "(docs/RESULTS.md, the figures the README quotes) they are much lower: e.g. $25.76 instead of $61.31 for "
          "Sonnet + sibling files. Our numeric answers make no paid calls; "
          "only the 110 free-text IFC questions call Claude Haiku. Local compute (CAD/IFC parsing on CPU, the YOLO "
          f"detector on one GPU, ~{drawing_s:.2f} s per drawing with flip test-time augmentation; the VLM arbiter only looks up "
          f"precomputed answers) prices at roughly ${compute_1k:.3f} per 1,000 questions at $0.50 per GPU-hour.",
          ""]

# --- one-off spend
lines += ["## What building it cost (one-off)", "", "| item | provider | $ |", "|---|---|---|"]
total = 0.0
dev = [
    ("Frontier baselines: Sonnet + Haiku + Sonnet with sibling files", "Anthropic (list price)",
     sum((run_cost(n) or (0, 0))[1] for n in ["baseline_sonnet_full400", "baseline_haiku_full400",
                                             "baseline_sonnet_test200", "sonnet_twins_affected284"])),
    ("Gemini baseline", "Google (list price)", (run_cost("baseline_gemini_full400") or (0, 0))[1]),
    ("Nemotron baseline (free endpoint; partner price shown)", "NVIDIA", (run_cost("baseline_nemotron_full400") or (0, 0))[1]),
    ("Text answers + LLM judge development (ifctext, pdftext, judge)", "Anthropic (list price)", ledger("cache/llm_spend.jsonl")),
    ("Generic fallback development (grounded boxes, text reading)", "Anthropic (list price)", ledger("cache/generic/spend.jsonl")),
]
for item, prov, c in dev:
    total += c
    lines.append(f"| {item} | {prov} | ${c:.2f} |")
infra = json.load(open("analysis/infra.json"))["machines"]
for m in infra:
    start = dt.datetime.fromisoformat(m["start"].replace("Z", "+00:00"))
    stop = dt.datetime.fromisoformat(m["stop"].replace("Z", "+00:00")) if m["stop"] else now
    h = (stop - start).total_seconds() / 3600
    c = h * m["usd_per_h"]
    total += c
    state = "" if m["stop"] else " (running)"
    lines.append(f"| {m['name']}: {m['what']}, {h:.1f} h × ${m['usd_per_h']}/h{state} | {m['provider']} | ${c:.2f} |")
lines += ["| YOLO detector training (~5 GPU-h on the homelab RTX 4070) | own hardware | ~$0 |",
          "| Codex independent audit of the evaluation | OpenAI | see OpenAI usage page |",
          f"| **Total so far** | | **${total:.2f}** |", "",
          "Everything above is a one-off: none of it grows with the number of questions answered.", ""]
Path("docs/COSTS.md").write_text("\n".join(lines))
print("\n".join(lines))
